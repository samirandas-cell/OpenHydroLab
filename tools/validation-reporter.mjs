/* Playwright reporter that collects every recorded verification case into a
   machine-readable validation dataset.

   Outputs, into validation/results/:
     validation-results.json  — one record per (case × browser engine)
     validation-results.md    — the tables used in the manuscript
     browser-matrix.json      — per-engine pass/fail counts for the software tests

   The point is that the numbers in the paper are generated by the run. Nothing is
   transcribed by hand, so the tables cannot drift away from the code. */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const OUT = resolve(ROOT, "validation/results");

const fmt = (v, sig = 6) => {
  if (!Number.isFinite(v)) return "—";
  if (v !== 0 && (Math.abs(v) < 1e-3 || Math.abs(v) >= 1e6)) return v.toExponential(3);
  return String(Number(v.toPrecision(sig)));
};

const fmtErr = (v) => {
  if (!Number.isFinite(v)) return "—";
  if (v === 0) return "0";
  if (v < 1e-9) return "< 1e-9";
  return v.toExponential(2);
};

export default class ValidationReporter {
  constructor() {
    this.cases = [];
    this.software = [];
    this.startedAt = new Date().toISOString();
  }

  onTestEnd(test, result) {
    try {
      for (const att of result.attachments) {
        if (att.name !== "validation-case" || !att.body) continue;
        try {
          this.cases.push(JSON.parse(att.body.toString("utf8")));
        } catch {
          /* a malformed record must not take the whole run down */
        }
      }

      const file = test.location?.file ?? "";
      if (file.split(/[\\/]/).includes("software")) {
        let engine = "unknown";
        try { engine = test.parent.project()?.name ?? "unknown"; } catch { /* older API */ }
        this.software.push({
          engine,
          title: test.title,
          file: file.split(/[\\/]/).pop() ?? "",
          status: result.status,
        });
      }
    } catch {
      /* reporting must never break the run */
    }
  }

  async onEnd(result) {
    mkdirSync(OUT, { recursive: true });

    const payload = {
      tool: "OpenHydroLab",
      generated: new Date().toISOString(),
      startedAt: this.startedAt,
      runStatus: result.status,
      engines: [...new Set(this.cases.map((c) => c.engine))].sort(),
      caseCount: this.cases.length,
      failures: this.cases.filter((c) => c.status === "fail").length,
      cases: this.cases,
    };
    writeFileSync(resolve(OUT, "validation-results.json"), JSON.stringify(payload, null, 2));

    /* ---- browser matrix ---- */
    const engines = payload.engines;
    const matrix = {};
    for (const s of this.software) {
      const key = `${s.file} › ${s.title}`;
      (matrix[key] ??= {})[s.engine] = s.status;
    }
    writeFileSync(
      resolve(OUT, "browser-matrix.json"),
      JSON.stringify({ generated: payload.generated, engines, tests: matrix }, null, 2),
    );

    /* ---- markdown tables for the manuscript ---- */
    const byModule = new Map();
    for (const c of this.cases) {
      if (!byModule.has(c.module)) byModule.set(c.module, new Map());
      const perId = byModule.get(c.module);
      // collapse engines: keep one row per case, note the worst error seen
      const prev = perId.get(c.id);
      if (!prev || (c.relErr || 0) > (prev.relErr || 0)) perId.set(c.id, c);
    }

    const lines = [];
    lines.push("# OpenHydroLab — numerical validation results");
    lines.push("");
    lines.push(`Generated ${payload.generated} · engines: ${engines.join(", ") || "none"}`);
    lines.push("");
    lines.push(
      `${payload.caseCount} recorded comparisons across ${byModule.size} modules and ` +
      `${engines.length} browser engine(s); ${payload.failures} failing.`,
    );
    lines.push("");
    lines.push(
      "Each row compares a value produced by the laboratory against a reference derived " +
      "independently of it — a closed-form solution, a conservation identity, or a " +
      "hand-checkable textbook calculation. Errors are the worst observed across engines.",
    );
    lines.push("");

    for (const [module, perId] of [...byModule].sort()) {
      lines.push(`## ${module}`);
      lines.push("");
      lines.push("| Case | Quantity | Reference | OpenHydroLab | Rel. error | Tolerance | Status |");
      lines.push("|---|---|---|---|---|---|---|");
      for (const c of [...perId.values()].sort((a, b) => a.id.localeCompare(b.id))) {
        const u = c.units ? ` ${c.units}` : "";
        lines.push(
          `| ${c.id} | ${c.quantity} | ${fmt(c.reference)}${u} | ${fmt(c.observed)}${u} | ` +
          `${fmtErr(c.relErr)} | ${c.tolerance} | ${c.status === "pass" ? "Pass" : "**Fail**"} |`,
        );
      }
      lines.push("");
      lines.push("<details><summary>Reference derivations</summary>");
      lines.push("");
      for (const c of [...perId.values()].sort((a, b) => a.id.localeCompare(b.id))) {
        lines.push(`- **${c.id}** — ${c.source}`);
      }
      lines.push("");
      lines.push("</details>");
      lines.push("");
    }

    if (Object.keys(matrix).length) {
      lines.push("## Cross-browser software test matrix");
      lines.push("");
      lines.push(`| Test | ${engines.join(" | ")} |`);
      lines.push(`|---|${engines.map(() => "---").join("|")}|`);
      for (const [name, res] of Object.entries(matrix).sort()) {
        const cells = engines.map((e) => {
          const s = res[e];
          if (!s) return "—";
          return s === "passed" ? "Pass" : s === "skipped" ? "Skip" : "**Fail**";
        });
        lines.push(`| ${name} | ${cells.join(" | ")} |`);
      }
      lines.push("");
    }

    writeFileSync(resolve(OUT, "validation-results.md"), lines.join("\n"));

    process.stdout.write(
      `\nValidation dataset written to ${dirname(resolve(OUT, "x"))}\n` +
      `  ${payload.caseCount} numerical comparisons, ${payload.failures} failing\n`,
    );
  }
}
